#!/usr/bin/env python3
"""Summarize run_bench.py output: per boot configuration and arm, the median and
range over the accepted windows. Writes summary.json and summary.md into the
same directory. Usage: bench_report.py DIR [DIR ...]
Reads DIR/windows.jsonl, or DIR/windows.jsonl.gz once it has been compressed.

Per command: KVM exits (all, MMIO, port I/O, HLT, the rest), the device's
doorbells, CQ head writes and MSI-X messages, and host CPU time of the QEMU
main loop (the device model) and of the vCPU threads, with the part the vCPU
threads spent in KVM's halt polling shown separately. Utilisation is CPU time
over window time. The idle arm has no commands; its counters are per window.
Runs with several builds (run_bench.py --builds) get one table per
configuration and build; bench_compare.py pairs them.
"""
import gzip
import json
import pathlib
import statistics
import sys


def window_metrics(w):
    g, k, d, t = w["guest"], w["kvm"], w["device"], w["threads"]
    cmds, ns = int(g["cmds"]), int(g["ns"])
    vcpu_ns = sum(v["run_ns"] for key, v in t.items() if key.startswith("vcpu"))
    poll_ns = k.get("halt_poll_success_ns", 0) + k.get("halt_poll_fail_ns", 0)
    clocks = [v for v in w["clock_mhz"].values() if v]
    secs = w["host_ns"] / 1e9
    m = {"foreign_ms_per_s": w["foreign_ms_per_s"], "clock_mhz": statistics.median(clocks) if clocks else None,
         "foreign_vm_cpus_ms_per_s": w["foreign_on_vm_cpus_ms"] / secs,
         "foreign_siblings_ms_per_s": w["foreign_on_siblings_ms"] / secs,
         "qemu_wait_ms_per_s": w["ours_wait_ms"] / secs,
         "main_util": t.get("main", {}).get("run_ns", 0) / w["host_ns"],
         "vcpu_util": vcpu_ns / w["host_ns"], "window_ms": ns / 1e6}
    other = k["exits"] - k["mmio_exits"] - k["io_exits"] - k["halt_exits"]
    if not cmds:  # idle arm: absolute counts per window
        m.update(exits=k["exits"], mmio=k["mmio_exits"], pio=k["io_exits"], halt=k["halt_exits"], other=other,
                 irqs=d["stat-irqs"])
        return m
    m.update(cmds=cmds, kcmd_s=cmds / ns * 1e6, lat_p10_us=int(g["lat_p10"]) / 1e3, lat_p50_us=int(g["lat_p50"]) / 1e3,
             lat_p90_us=int(g["lat_p90"]) / 1e3, lat_p99_us=int(g["lat_p99"]) / 1e3,
             exits=k["exits"] / cmds, mmio=k["mmio_exits"] / cmds, pio=k["io_exits"] / cmds,
             halt=k["halt_exits"] / cmds, other=other / cmds,
             sq_doorbells=d["stat-doorbells"] / cmds, cq_doorbells=d["stat-cq-doorbells"] / cmds,
             irqs=d["stat-irqs"] / cmds, main_us=t.get("main", {}).get("run_ns", 0) / 1e3 / cmds,
             vcpu_us=vcpu_ns / 1e3 / cmds, halt_poll_us=poll_ns / 1e3 / cmds,
             queues=bin(int(g["queues"], 16)).count("1"))
    return m


def summarize(windows):
    groups = {}
    for w in windows:
        groups.setdefault((w["config"], w.get("build", "tree"), w["guest"]["arm"]), []).append(w)
    out = []
    for (config, build, arm), ws in groups.items():
        ok = [window_metrics(w) for w in ws if w["accepted"]]
        entry = {"config": config, "build": build, "arm": arm, "accepted": len(ok),
                 "rejected": sum(not w["accepted"] for w in ws), "metrics": {}}
        for key in (ok[0] if ok else {}):
            vals = [m[key] for m in ok if m.get(key) is not None]
            if vals:
                entry["metrics"][key] = {"median": statistics.median(vals), "min": min(vals), "max": max(vals)}
        out.append(entry)
    return out


def fmt(v, digits):
    return "-" if v is None else f"{v:.{digits}f}"


def cell(e, key, digits, spread=False):
    m = e["metrics"].get(key)
    if not m:
        return "-"
    text = fmt(m["median"], digits)
    return f"{text} ({fmt(m['min'], digits)}-{fmt(m['max'], digits)})" if spread else text


def markdown(entries, title):
    lines = [f"# {title}", "",
             "Medians over accepted windows, (min-max) where shown. Per command unless noted. "
             "Generated by scripts/bench_report.py from windows.jsonl.", ""]
    builds = list(dict.fromkeys(e["build"] for e in entries))
    for config, build in dict.fromkeys((e["config"], e["build"]) for e in entries):
        rows = [e for e in entries if e["config"] == config and e["build"] == build]
        lines += [f"## {config}" + (f", build {build}" if len(builds) > 1 else ""), "",
                  "| arm | n | k cmds/s | p50 us | p99 us | exits | MMIO | HLT | other | SQ db | CQ db | MSI-X "
                  "| main loop us | main util | vCPU us | of it halt-poll us |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for e in rows:
            if "kcmd_s" not in e["metrics"]:
                continue
            lines.append(f"| {e['arm']} | {e['accepted']} | {cell(e, 'kcmd_s', 1, True)} | {cell(e, 'lat_p50_us', 1, True)} "
                         f"| {cell(e, 'lat_p99_us', 1)} | {cell(e, 'exits', 2)} | {cell(e, 'mmio', 2)} | {cell(e, 'halt', 2)} "
                         f"| {cell(e, 'other', 2)} | {cell(e, 'sq_doorbells', 2)} | {cell(e, 'cq_doorbells', 2)} "
                         f"| {cell(e, 'irqs', 2)} | {cell(e, 'main_us', 2)} | {cell(e, 'main_util', 2)} "
                         f"| {cell(e, 'vcpu_us', 2)} | {cell(e, 'halt_poll_us', 2)} |")
        idle = [e for e in rows if "kcmd_s" not in e["metrics"] and e["metrics"]]
        if idle:
            lines += ["", "Idle windows (no commands), counts per window:", "",
                      "| arm | n | window ms | exits | MMIO | PIO | HLT | other | MSI-X |", "|---|---|---|---|---|---|---|---|---|"]
            for e in idle:
                lines.append(f"| {e['arm']} | {e['accepted']} | {cell(e, 'window_ms', 0)} | {cell(e, 'exits', 0, True)} "
                             f"| {cell(e, 'mmio', 0)} | {cell(e, 'pio', 0)} | {cell(e, 'halt', 0)} | {cell(e, 'other', 0)} "
                             f"| {cell(e, 'irqs', 0)} |")
        rejected = sum(e["rejected"] for e in rows)

        def worst(key):
            vals = [e["metrics"][key]["max"] for e in rows if key in e["metrics"]]
            return fmt(max(vals) if vals else None, 1)

        clocks = [e["metrics"]["clock_mhz"] for e in rows if "clock_mhz" in e["metrics"]]
        lines += ["", f"Windows rejected for foreign load: {rejected}. Largest accepted foreign CPU time on the "
                      f"watched CPUs: {worst('foreign_ms_per_s')} ms/s ({worst('foreign_vm_cpus_ms_per_s')} on the "
                      f"CPUs running QEMU threads, {worst('foreign_siblings_ms_per_s')} on their SMT siblings); "
                      f"QEMU threads waiting for a CPU: at most {worst('qemu_wait_ms_per_s')} ms/s. "
                      f"Host clock of the VM's CPUs (median per window): "
                      f"{fmt(min(c['min'] for c in clocks) if clocks else None, 0)}-"
                      f"{fmt(max(c['max'] for c in clocks) if clocks else None, 0)} MHz.", ""]
    return "\n".join(lines) + "\n"


def main():
    for arg in sys.argv[1:]:
        d = pathlib.Path(arg)
        raw = d / "windows.jsonl"
        text = raw.read_text() if raw.exists() else gzip.decompress((d / "windows.jsonl.gz").read_bytes()).decode()
        windows = [json.loads(line) for line in text.splitlines() if line.strip()]
        entries = summarize(windows)
        (d / "summary.json").write_text(json.dumps(entries, indent=2) + "\n")
        (d / "summary.md").write_text(markdown(entries, f"Benchmark summary: {d.name}"))
        print(f"{d}: {len(windows)} windows, {len(entries)} arms")


if __name__ == "__main__":
    main()
